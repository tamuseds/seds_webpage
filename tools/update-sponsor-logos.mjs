import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const directory = new URL('../images/sponsorlogos/', import.meta.url);
const files = await readdir(directory, { withFileTypes: true });
const logos = files
  .filter((file) => file.isFile() && /\.(svg|png|jpe?g|webp|gif|avif)$/i.test(file.name))
  .map((file) => ({
    file: file.name,
    name: file.name.replace(/\.[^.]+$/, '').replace(/[-_]+/g, ' '),
  }))
  .sort((a, b) => a.file.localeCompare(b.file, 'en', { numeric: true }));

for (const logo of logos) {
  logo.version = createHash('sha256')
    .update(await readFile(new URL(encodeURIComponent(logo.file), directory)))
    .digest('hex').slice(0, 16);
}

await writeFile(new URL('logos.js', directory),
  '// Generated by: node tools/update-sponsor-logos.mjs\n' +
  'window.SPONSOR_LOGOS = ' + JSON.stringify(logos, null, 2) + ';\n');
console.log(`Updated sponsor list: ${logos.length} logo(s).`);
